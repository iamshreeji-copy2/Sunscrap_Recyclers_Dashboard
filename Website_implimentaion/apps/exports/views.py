@login_required
def downloads_view(request):
    jobs = ExportJob.objects.all().order_by('-created_at')[:50]
    return render(request, 'reports/downloads.html', {'jobs': jobs})

@login_required
def schedules_view(request):
    if request.method == 'POST':
        action = request.POST.get('action')
        if action == 'create':
            name = request.POST.get('name', 'Automated Daily Report')
            report_type = request.POST.get('report_type', 'summary')
            period = request.POST.get('period', 'daily')
            interval = request.POST.get('interval', '15min')
            recipients = request.POST.get('recipients', '')
            export_format = request.POST.get('export_format', 'xlsx')
            
            ReportSchedule.objects.create(
                name=name,
                report_type=report_type,
                period=period,
                interval=interval,
                recipients=recipients,
                export_format=export_format,
                created_by=request.user
            )
            return redirect('schedules')
        elif action == 'toggle':
            sched_id = request.POST.get('schedule_id')
            sched = get_object_or_404(ReportSchedule, id=sched_id)
            sched.is_active = not sched.is_active
            sched.save()
            return redirect('schedules')
            
    schedules = ReportSchedule.objects.all().order_by('-created_at')
    return render(request, 'reports/schedules.html', {'schedules': schedules})

@login_required
def download_file_view(request, job_id):
    job = get_object_or_404(ExportJob, job_id=job_id)
    if not job.is_downloadable:
        raise Http404("This export file is either unavailable, still processing, or has expired.")
        
    mime_type, _ = mimetypes.guess_type(job.file_path)
    if not mime_type:
        mime_type = 'application/octet-stream'
        
    filename = os.path.basename(job.file_path)
    with open(job.file_path, 'rb') as f:
        response = HttpResponse(f.read(), content_type=mime_type)
        response['Content-Disposition'] = f'attachment; filename="{filename}"'
        response['Content-Length'] = job.file_size_bytes
        return response

@login_required
def retry_job_view(request, job_id):
    job = get_object_or_404(ExportJob, job_id=job_id)
    process_export_job(job)
    return redirect('downloads')

@login_required
def email_report_view(request):
    if request.method == 'POST':
        snapshot_id = request.POST.get('snapshot_id')
        recipients_raw = request.POST.get('recipients', '')
        subject = request.POST.get('subject', 'SATs Solar SCADA Report')
        fmt = request.POST.get('format', 'xlsx').lower()
        
        snapshot = get_object_or_404(ReportSnapshot, snapshot_id=snapshot_id)
        recipients = [r.strip() for r in recipients_raw.split(',') if r.strip()]
        
        # Create job
        job = ExportJob.objects.create(
            snapshot=snapshot,
            export_format=fmt,
            requester=request.user
        )
        success, msg = process_export_job(job)
        
        if success and recipients:
            email = EmailMessage(
                subject=subject,
                body=f"Hello,\n\nPlease find attached the {snapshot.title} for {snapshot.period_label}.\n\nGenerated by SATs Solar SCADA (SAT Solutions).\nData as of: {snapshot.data_as_of}",
                from_email="reports@satsolutions.in",
                to=recipients
            )
            email.attach_file(job.file_path)
            try:
                email.send(fail_silently=False)
                return JsonResponse({'status': 'SUCCESS', 'message': f'Report emailed to {", ".join(recipients)}'})
            except Exception as e:
                return JsonResponse({'status': 'ERROR', 'message': f'Email sending error: {str(e)}'}, status=500)
                
        return JsonResponse({'status': 'ERROR', 'message': msg}, status=500)
    return JsonResponse({'status': 'BAD_REQUEST'}, status=400)
